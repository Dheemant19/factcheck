"""Main results table v1 (T21) for the Week 12 consultation, straight from results/runs.csv.

    python notebooks/02_results_v1.py

Writes, with no number typed by hand:

    results/results_v1_table.md            mean ± std test macro-F1 per model family and dataset
    results/figures/v1_macro_f1.png        the same, as bars with seed error bars
    results/figures/v1_cost.png            test macro-F1 vs trainable parameters (full, LoRA, QLoRA)
    results/figures/v1_llm_modes.png       Qwen3-8B zero-shot, kNN few-shot, RAG and QLoRA
    results/figures/v1_optuna.png          Optuna hyperparameter importance (T18)

Within a family (for example "large / domain encoder") the run shown is the one with the best
mean VALIDATION macro-F1, so the test set never picks a model. Scores are on the full test set
(ISOT: the cleaned text); runs with fewer than 3 seeds are marked.
"""

from __future__ import annotations

import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from factcheck.paths import FIGURES_DIR, RESULTS_DIR  # noqa: E402
from factcheck.results import load_runs  # noqa: E402

DATASETS = {"covid": "COVID", "liar": "LIAR", "pubhealth": "PUBHEALTH", "isot": "ISOT (cleaned)"}
BASE = ("distilbert", "bert", "roberta", "deberta_v3_base", "modernbert")
LARGE = ("roberta_large", "deberta_v3_large", "covid_twitter_bert", "scibert")
# family -> run names for one dataset (ISOT encoders use the cleaned variant)
FAMILIES = {
    "Bi-LSTM (GloVe)": lambda d: [f"lstm_{d}"],
    "kNN vote (bge-small)": lambda d: [f"knn_bge_small_{d}"],
    "Qwen3-8B zero-shot": lambda d: [f"qwen3_8b_zeroshot_{d}"],
    "Qwen3-8B kNN few-shot": lambda d: [f"qwen3_8b_knn_{d}"],
    "Qwen3-8B evidence RAG": lambda d: [f"qwen3_8b_rag_{d}"],
    "Base encoder": lambda d: [f"{m}_{d}{'_clean' if d == 'isot' else ''}" for m in BASE],
    "Large / domain encoder": lambda d: [
        f"{m}_{d}{'_clean' if d == 'isot' else ''}" for m in LARGE
    ],
    "LoRA, large encoder": lambda d: [
        f"{m}_lora_r{r}_{t}_{d}"
        for m in ("roberta_large", "deberta_v3_large")
        for r in (4, 16, 64)
        for t in ("attn", "all")
    ],
    "Optuna-tuned DeBERTa-v3-base": lambda d: [f"deberta_v3_base_{d}_tuned"],
    "Tuned + one extra (metadata / evidence / class weights)": lambda d: [
        f"deberta_v3_base_{d}_tuned_{x}" for x in ("meta", "evidence", "cw")
    ],
    "Qwen3-8B QLoRA": lambda d: [f"qwen3_8b_qlora_{d}"],
}
PUBLISHED = {"pubhealth": ("Kotonya & Toni 2020, SciBERT", 0.7052)}  # same metric (macro-F1)

INK, MUTED, GRID, SURFACE = "#13294b", "#52514e", "#e1e0d9", "#fcfcfb"
BLUE, ORANGE, AQUA, YELLOW = "#2a78d6", "#eb6834", "#1baf7a", "#eda100"


def scores(runs: pd.DataFrame) -> pd.DataFrame:
    """Mean and std over seeds per run: test macro-F1 (full test set) and validation macro-F1."""
    full = runs[runs["subset"].isna()]
    key = ["dataset", "run_name"]
    test = full[full["split"] == "test"].groupby(key)
    val = full[full["split"] == "validation"].groupby(key)["macro_f1"].mean().rename("val_f1")
    out = test.agg(
        f1=("macro_f1", "mean"),
        sd=("macro_f1", "std"),
        acc=("accuracy", "mean"),
        seeds=("seed", "nunique"),
        params=("trainable_params", "first"),
        model=("model_name", "first"),
        method=("method", "first"),
    )
    return out.join(val).reset_index()


def family_table(per_run: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for dataset in DATASETS:
        runs = per_run[per_run["dataset"] == dataset].set_index("run_name")
        for family, names in FAMILIES.items():
            found = runs.loc[runs.index.intersection(names(dataset))]
            if found.empty:
                continue
            pick = found["val_f1"].fillna(found["f1"]).idxmax()  # chosen on validation
            rows.append({"dataset": dataset, "family": family, "run": pick, **found.loc[pick]})
    return pd.DataFrame(rows)


def cell(row: pd.Series) -> str:
    sd = f" ± {row['sd']:.3f}" if row["seeds"] > 1 else ""
    flag = "" if row["seeds"] >= 3 else f" ({int(row['seeds'])} seed)"
    return f"{row['f1']:.3f}{sd}{flag}"


def write_table(table: pd.DataFrame) -> None:
    wide = table.assign(text=table.apply(cell, axis=1)).pivot(
        index="family", columns="dataset", values="text"
    )
    wide = wide.reindex(index=[f for f in FAMILIES if f in wide.index], columns=list(DATASETS))
    wide = wide.rename(columns=DATASETS).fillna("–")
    runs = table.pivot(index="family", columns="dataset", values="run").reindex(wide.index)
    lines = [
        "# Main results v1: test macro-F1, mean ± std over seeds (13, 42, 2026)",
        "",
        "Generated by `notebooks/02_results_v1.py` from `results/runs.csv`. Within each family "
        "the run with the best validation macro-F1 is shown.",
        "",
        "| Family | " + " | ".join(wide.columns) + " |",
        "|---" * (len(wide.columns) + 1) + "|",
    ]
    for family, row in wide.iterrows():
        lines.append(f"| {family} | " + " | ".join(row) + " |")
    lines += ["", "Runs shown:", ""]
    for family, row in runs.iterrows():
        lines.append(f"- {family}: " + ", ".join(r for r in row.dropna()))
    lines += [
        "",
        f"Published, same metric: PUBHEALTH macro-F1 {PUBLISHED['pubhealth'][1]:.4f} "
        f"({PUBLISHED['pubhealth'][0]}).",
    ]
    (RESULTS_DIR / "results_v1_table.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def style(ax: plt.Axes) -> None:
    ax.set_facecolor(SURFACE)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color("#c3c2b7")
    ax.tick_params(colors=MUTED, labelsize=11, length=0)
    ax.grid(axis="x", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def plot_macro_f1(table: pd.DataFrame) -> None:
    panels = ("covid", "liar", "pubhealth")
    fig, axes = plt.subplots(1, 3, figsize=(16, 6.2), facecolor=SURFACE, sharey=True)
    order = [f for f in FAMILIES if f != "Tuned + one extra (metadata / evidence / class weights)"]
    order.append("Tuned + one extra (metadata / evidence / class weights)")
    labels = [f.replace(" (metadata / evidence / class weights)", " (best extra)") for f in order]
    for ax, dataset in zip(axes, panels, strict=True):
        style(ax)
        part = table[table["dataset"] == dataset].set_index("family").reindex(order)
        y = np.arange(len(order))[::-1]
        best = part["f1"].max()
        colors = [ORANGE if v == best else BLUE for v in part["f1"].fillna(-1)]
        ax.barh(y, part["f1"].fillna(0), height=0.62, color=colors, edgecolor=SURFACE)
        ax.errorbar(
            part["f1"], y, xerr=part["sd"].fillna(0), fmt="none", ecolor=INK, elinewidth=1.2
        )
        for yi, (_, row) in zip(y, part.iterrows(), strict=True):
            if pd.isna(row["f1"]):
                ax.text(0.01, yi, "not run", va="center", fontsize=10, color=MUTED)
                continue
            mark = "" if row["seeds"] >= 3 else " (1 seed)"
            ax.text(
                row["f1"] + (row["sd"] if row["seeds"] > 1 else 0) + 0.01,
                yi,
                f"{row['f1']:.3f}{mark}",
                va="center",
                fontsize=10.5,
                color=INK,
            )
        if dataset in PUBLISHED:
            name, value = PUBLISHED[dataset]
            ax.axvline(value, color=INK, linestyle="--", linewidth=1.2)
            ax.text(value, len(order) - 0.2, f"published {value:.3f}", fontsize=10, color=INK)
        ax.set_title(DATASETS[dataset], fontsize=15, color=INK, loc="left", fontweight="bold")
        ax.set_xlim(0, 1.15)
        ax.set_yticks(y, labels)
        ax.set_xlabel("Test macro-F1 (mean ± std over 3 seeds)", fontsize=11, color=MUTED)
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "v1_macro_f1.png", dpi=150, facecolor=SURFACE)
    plt.close(fig)


def plot_cost(per_run: pd.DataFrame) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(14, 5.6), facecolor=SURFACE)
    kinds = {"full": ("Full fine-tuning", BLUE, "o"), "lora": ("LoRA", ORANGE, "s")}
    kinds["qlora"] = ("QLoRA, Qwen3-8B", AQUA, "D")
    for ax, dataset in zip(axes, ("liar", "pubhealth"), strict=True):
        style(ax)
        ax.grid(axis="y", color=GRID, linewidth=0.8)
        part = per_run[(per_run["dataset"] == dataset) & per_run["params"].gt(0)]
        part = part[~part["run_name"].str.startswith("lstm")]
        for method, (name, color, marker) in kinds.items():
            sel = part[part["method"] == method]
            ax.scatter(
                sel["params"], sel["f1"], s=70, color=color, marker=marker, label=name,
                edgecolor=SURFACE, linewidth=1.5, zorder=3,
            )  # fmt: skip
        for method in ("full", "lora"):
            sel = part[part["method"] == method]
            top = sel.loc[sel["f1"].idxmax()]
            ax.annotate(
                f"{top['run_name'].replace('_' + dataset, '')}\n{top['f1']:.3f}",
                (top["params"], top["f1"]),
                xytext=(8, 8),
                textcoords="offset points",
                fontsize=10,
                color=INK,
            )
        ax.set_xscale("log")
        ax.set_xlabel("Trainable parameters (log scale)", fontsize=11, color=MUTED)
        ax.set_ylabel("Test macro-F1", fontsize=11, color=MUTED)
        ax.set_title(DATASETS[dataset], fontsize=15, color=INK, loc="left", fontweight="bold")
        ax.legend(frameon=False, fontsize=10, labelcolor=INK, loc="lower right")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "v1_cost.png", dpi=150, facecolor=SURFACE)
    plt.close(fig)


def plot_llm_modes(per_run: pd.DataFrame) -> None:
    modes = {
        "zeroshot": ("Zero-shot", BLUE),
        "knn": ("kNN few-shot (8 fact-checks)", ORANGE),
        "rag": ("Evidence RAG", AQUA),
        "qlora": ("QLoRA (trained)", YELLOW),
    }
    datasets = ("covid", "liar", "pubhealth")
    fig, ax = plt.subplots(figsize=(13, 5.4), facecolor=SURFACE)
    style(ax)
    ax.grid(axis="x", visible=False)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    width = 0.2
    for i, (method, (name, color)) in enumerate(modes.items()):
        values = []
        for dataset in datasets:
            row = per_run[(per_run["dataset"] == dataset) & (per_run["method"] == method)]
            row = row[row["run_name"].str.startswith("qwen3_8b")]
            values.append(row["f1"].max() if len(row) else np.nan)
        x = np.arange(len(datasets)) + (i - 1.5) * width
        ax.bar(x, np.nan_to_num(values), width=width - 0.02, color=color, label=name)
        for xi, v in zip(x, values, strict=True):
            ax.text(
                xi, (0 if np.isnan(v) else v) + 0.015, "–" if np.isnan(v) else f"{v:.2f}",
                ha="center", fontsize=10.5, color=INK,
            )  # fmt: skip
    ax.set_xticks(np.arange(len(datasets)), [DATASETS[d] for d in datasets], fontsize=13)
    ax.set_ylim(0, 1.18)
    ax.set_yticks(np.arange(0, 1.01, 0.2))
    ax.set_ylabel("Test macro-F1 (seed 42)", fontsize=11, color=MUTED)
    ax.legend(frameon=False, fontsize=11, labelcolor=INK, ncol=4, loc="upper center")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "v1_llm_modes.png", dpi=150, facecolor=SURFACE)
    plt.close(fig)


def plot_optuna() -> None:
    datasets = ("covid", "liar", "pubhealth")
    imps = {}
    for d in datasets:
        path = RESULTS_DIR / "optuna" / f"deberta_v3_base_{d}_importance.json"
        imps[d] = json.loads(path.read_text(encoding="utf-8"))
    params = sorted(
        {p for v in imps.values() for p in v}, key=lambda p: -imps["pubhealth"].get(p, 0)
    )
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.8), facecolor=SURFACE, sharey=True)
    for ax, d in zip(axes, datasets, strict=True):
        style(ax)
        values = [imps[d].get(p, 0.0) for p in params]
        y = np.arange(len(params))[::-1]
        ax.barh(y, values, height=0.6, color=BLUE)
        for yi, v in zip(y, values, strict=True):
            ax.text(v + 0.01, yi, f"{v:.2f}", va="center", fontsize=10.5, color=INK)
        ax.set_yticks(y, [p.replace("_", " ") for p in params], fontsize=12)
        ax.set_xlim(0, 0.8)
        ax.set_title(DATASETS[d], fontsize=15, color=INK, loc="left", fontweight="bold")
        ax.set_xlabel("fANOVA importance (sums to 1)", fontsize=11, color=MUTED)
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "v1_optuna.png", dpi=150, facecolor=SURFACE)
    plt.close(fig)


def main() -> None:
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    per_run = scores(load_runs())
    table = family_table(per_run)
    write_table(table)
    plot_macro_f1(table)
    plot_cost(per_run)
    plot_llm_modes(per_run)
    plot_optuna()
    print((RESULTS_DIR / "results_v1_table.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
